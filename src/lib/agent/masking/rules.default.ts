/** Правила по типу (для панели справочника и отчётов). */
export function defaultRulesByType(): Record<string, number> {
  const counts: Record<string, number> = {};
  for (const rule of DEFAULT_DETECTOR_RULES) {
    counts[rule.type] = (counts[rule.type] ?? 0) + 1;
  }
  return counts;
}
